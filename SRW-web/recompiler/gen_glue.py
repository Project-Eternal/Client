#!/usr/bin/env python3
"""Generate the glue between the recompiled program and the runtime.

usage: gen_glue.py RECOMPILED_DIR [--trace 0|1|2] [--defs FILE...] [--dynamic FILE...] [--src DIR...]

With TRACE = 1 every import logs its name when called (SRW_Trace_c), for finding out what the program is doing; with 2 (the diagnostics
build) the call is only recorded for the watchdog (the last import and its caller of every thread).

Reads imports.txt and entry.txt (written by split_llasm.py) and writes, into RECOMPILED_DIR:
  glue.llasm       a procedure for every import, and the C-callable entry point (c_SRW_Entry)
  imports.h        prototypes of the C functions that implement imports
  imports.c        the names of the imports, for the messages of the stubs

An import is implemented by a C function `<name>_c` (a '.' in the name becomes '_'), declared with CCALL in one of the
source files of the --src folders; imports.h has the exact prototype. The procedure then reads the stdcall arguments from the guest
stack, calls the function, leaves its result in eax and removes the arguments. An import without such a function gets a
stub that reports which function was called.

This runs in a moment, unlike the recompilation, so adding an implementation does not repeat that.
"""
import os
import re
import sys

HEADER = ["include llasm.llinc", "include extern.llinc", "include macros.llinc", "include asm-calls.llinc", ""]


# imports that use the cdecl convention (the caller removes the arguments) and take a variable number of them: the
# implementation receives a pointer to the arguments on the guest stack
CDECL_VARARGS = {"wsprintfA"}
# a definition file may add to these with directives: @cdecl-fixed NAME... (fixed arguments that the caller removes) and
# @float-return NAME... (the result is a float in st(0): the C function returns its bits)
CDECL_FIXED = set()
FLOAT_RETURNS = set()
# macros that define the C function of an import: the name of the macro, its first argument is the import (@implemented-by-macro NAME...)
IMPLEMENTING_MACROS = set()


def load_import_defs(path):
    defs = {}
    for line in open(path):
        parts = line.split()
        if parts and parts[0] == "@cdecl-fixed":
            CDECL_FIXED.update(parts[1:])
        elif parts and parts[0] == "@implemented-by-macro":
            IMPLEMENTING_MACROS.update(parts[1:])
        elif parts and parts[0] == "@float-return":
            FLOAT_RETURNS.update(parts[1:])
        elif len(parts) >= 3 and not parts[0].startswith("#"):
            defs[parts[0]] = (parts[1], int(parts[2]), parts[3:])
    return defs


def find_implementations(srcdirs):
    found = set()
    rx = re.compile(r"\bCCALL\s+(\w+)_c\s*\(")
    # functions written with a macro (NAME(import, params...) defines import_c)
    macro_rx = re.compile(r"^(?:%s)\((\w+)" % "|".join(sorted(IMPLEMENTING_MACROS)) if IMPLEMENTING_MACROS else r"(?!)", re.M)
    for srcdir in srcdirs:
        for name in os.listdir(srcdir):
            if name.endswith((".c", ".cpp")):
                text = open(os.path.join(srcdir, name), errors="ignore").read()
                found.update(rx.findall(text))
                found.update(macro_rx.findall(text))
    return found


def declare(decls, declared, line):
    # a C function is declared once, however many procedures call it
    name = line.split()[1]
    if name not in declared:
        declared.add(name)
        decls.append(line)


def c_name(import_name):
    return import_name.replace(".", "_")


def main(outdir, def_paths, dynamic_paths, srcdirs, trace=False):
    imports = open(os.path.join(outdir, "imports.txt")).read().split()
    entry_proc = open(os.path.join(outdir, "entry.txt")).read().strip()
    defs = {}
    for path in def_paths:
        defs.update(load_import_defs(path))
    dynamic = []
    for dyn_path in dynamic_paths:
        dyn_defs = load_import_defs(dyn_path)
        defs.update(dyn_defs)
        dynamic += [n for n in dyn_defs if n not in dynamic]
    imports = imports + [n for n in dynamic if n not in imports]
    implemented = find_implementations(srcdirs)

    proto = ["#ifndef SRW_IMPORTS_H", "#define SRW_IMPORTS_H", "", "#include <stdint.h>", '#include "srw.h"', "",
             "/* generated by gen_glue.py from imports.def: the C function behind each import; the result is returned in",
             "   eax, pointers arrive as guest addresses converted for the call, 64-bit values as low and high words */",
             "", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    decls, bodies = [], []
    declared = set()
    wrapped = known = 0
    for i, n in enumerate(imports):
        bare = n[len("srw_"):] if n.startswith("srw_") else n  # split_llasm.py prefixes the names of the imports
        bare = bare[len("ws2_32."):] if bare.startswith("ws2_32.") else bare
        dll, nargs, kinds = defs.get(bare, (None, -1, []))
        cn = c_name(bare)
        expanded = []
        if nargs >= 0:
            known += 1
            # one C parameter per 32-bit stack slot
            for k in kinds:
                expanded += [k, "i"] if k in ("q", "d") else [k]
            if len(expanded) != nargs:
                expanded = ["i"] * nargs
            if bare in CDECL_VARARGS:
                proto.append("uint32_t CCALL %s_c(const uint32_t *args);" % cn)
            elif nargs <= 8:
                params = ", ".join(("void *a%d" if e == "p" else "const char *a%d" if e == "s" else
                                    "const uint16_t *a%d" if e == "w" else "uint32_t a%d") % (j) for j, e in enumerate(expanded))
                proto.append("uint32_t CCALL %s_c(%s);" % (cn, params or "void"))
            else:
                proto.append("uint32_t CCALL %s_c(const uint32_t *args);" % cn)

        # the import and the guest address that called it (the return address on the stack), for the watchdog of the diagnostics build
        tr = ["        mov tmp0, %d" % i, "        load tmp1, esp, 4", "        call SRW_Trace_c tmp0, tmp1"] if trace else []
        if cn in implemented and nargs >= 0:
            wrapped += 1
            if bare in CDECL_VARARGS:
                declare(decls, declared, "func %s_c *args" % cn)
                bodies += ["proc %s public" % n] + tr + ["        add tmp0, esp, 4", "        call %s_c tmp0" % cn,
                           "        mov eax, tmp0", "        Call_Asm_Return 0", "endp", ""]
            elif nargs <= 8:
                declare(decls, declared, "func %s_c %s" % (cn, ", ".join(("*a%d" if e in "psw" else "a%d") % j for j, e in enumerate(expanded))))
                bodies += ["proc %s public" % n] + tr + ["        Call_Asm_Stack%d %s_c" % (nargs, cn)]
                if bare in FLOAT_RETURNS:
                    bodies += ["        FLD_FLOAT eax"]
                bodies += ["        Call_Asm_Return %d" % (0 if bare in CDECL_FIXED else nargs), "endp", ""]
            else:
                declare(decls, declared, "func %s_c *args" % cn)
                bodies += ["proc %s public" % n] + tr + ["        add tmp0, esp, 4", "        call %s_c tmp0" % cn,
                           "        mov eax, tmp0", "        Call_Asm_Return %d" % nargs, "endp", ""]
        elif n.startswith(("IDirect3D", "IUnknown_")):
            # a method of a Direct3D object that is not implemented: the caller is told so and the program goes on
            bodies += ["proc %s public" % n] + tr + ["        mov tmp0, %d" % i, "        call SRW_D3DStub_c tmp0", "        mov eax, tmp0",
                       "        Call_Asm_Return %d" % max(nargs, 0), "endp", ""]
        else:
            bodies += ["proc %s public" % n, "        mov tmp0, %d" % i, "        call SRW_Unimplemented_c tmp0",
                       "        Call_Asm_Return %d" % max(nargs, 0), "endp", ""]
    proto += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]

    out = HEADER + decls + [""] + bodies
    out += ["proc %s external" % entry_proc, "", "proc SRW_Entry_c2asm global c_SRW_Entry",
            "        tcall %s" % entry_proc, "endp", "",
            "; runs the guest procedure whose address is in eax (SRW_CallGuest prepares the stack)",
            "proc SRW_CallGuest_c2asm global c_SRW_CallGuest", "        tcall eax", "endp"]
    if dynamic:
        # what GetProcAddress hands out: the guest address of the procedure of each name, with the module it belongs to
        out += ["datasegment .dynexp", "dlabel SRW_DynamicExportAddresses global"] + ["daddr %s" % n for n in dynamic] + ["endd", ""]

    def write(name, text):
        # leave the file alone when nothing changed, so that nothing depending on it is rebuilt
        path = os.path.join(outdir, name)
        if os.path.isfile(path) and open(path).read() == text:
            return
        with open(path, "w") as f:
            f.write(text)

    write("glue.llasm", "\n".join(out) + "\n")
    write("imports.h", "\n".join(proto))
    names = "#include <stdint.h>\n\nconst char *const SRW_ImportNames[] = {\n" + "".join('    "%s",\n' % (n[4:] if n.startswith("srw_") else n) for n in imports)
    names += "};\n\nconst uint32_t SRW_ImportCount = %d;\n" % len(imports)
    if dynamic:
        names += "\nconst char *const SRW_DynamicExportNames[] = {\n" + "".join('    "%s",\n' % n for n in dynamic) + "};\n"
        names += "\nconst char *const SRW_DynamicExportModules[] = {\n" + "".join('    "%s",\n' % defs[n][0] for n in dynamic) + "};\n"
        names += "\nconst uint32_t SRW_DynamicExportCount = %d;\n" % len(dynamic)
    write("imports.c", names)
    print("imports: %d, with a signature: %d, implemented: %d" % (len(imports), known, wrapped), file=sys.stderr)


if __name__ == "__main__":
    args = {"--trace": [], "--defs": [], "--dynamic": [], "--src": []}
    current = None
    for a in sys.argv[2:]:
        if a in args:
            current = a
        elif current is None:
            raise SystemExit(__doc__)
        else:
            args[current].append(a)
    main(sys.argv[1], args["--defs"], args["--dynamic"], args["--src"], trace=bool(args["--trace"]) and args["--trace"][0] in ("1", "2"))
