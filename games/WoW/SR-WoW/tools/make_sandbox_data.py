#!/usr/bin/env python3
"""Generates WoW-sandbox-data.inc (teleport places, area triggers and emotes of the sandbox) from the sources of AIO Sandbox
(https://github.com/barncastle/AIO-Sandbox, MIT license, (c) 2020 barncastle): Common/Resources/*.csv and Common/Constants/Emotes.cs.

usage: make_sandbox_data.py /path/to/AIO-Sandbox > WoW-sandbox-data.inc
Only what applies to Vanilla is kept (expansion 0 = pre-release and 1 = Vanilla)."""
import re
import sys

root = sys.argv[1]


def c_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def f(text):
    """a float literal of C"""
    return repr(float(text)) + 'f'


def csv_lines(name):
    with open(root + '/Common/Resources/' + name, encoding='utf-8-sig') as f:
        return [line.strip('\r\n') for line in f if line.strip()]


print('/* generated by tools/make_sandbox_data.py from AIO Sandbox (MIT, barncastle): do not edit */')

# worldports: x,y,z,o,map,description,expansion
print('static const SandboxPlace sandbox_worldports[] = {')
count = 0
for line in csv_lines('Worldports.csv'):
    fields = line.split(',')
    if int(fields[-1]) > 1:
        continue
    description = ','.join(fields[5:-1])
    print('    {%s, %s, %s, %s, %s, %s},' % (f(fields[0]), f(fields[1]), f(fields[2]), f(fields[3]), fields[4], c_string(description)))
    count += 1
print('};\n#define SANDBOX_WORLDPORT_COUNT %d\n' % count)

# area triggers: id,x,y,z,o,map,description,expansion (the newest variant of an id that applies wins)
triggers = {}
for line in csv_lines('AreaTriggers.csv'):
    fields = line.split(',')
    expansion = int(fields[-1])
    if expansion > 1:
        continue
    identifier = int(fields[0])
    if identifier not in triggers or triggers[identifier][0] < expansion:
        triggers[identifier] = (expansion, fields[1:5], fields[5], ','.join(fields[6:-1]))
print('static const SandboxTrigger sandbox_triggers[] = {')
for identifier in sorted(triggers):
    expansion, xyzo, map_id, description = triggers[identifier]
    print('    {%d, {%s, %s, %s, %s, %s, %s}},' % (identifier, f(xyzo[0]), f(xyzo[1]), f(xyzo[2]), f(xyzo[3]), map_id, c_string(description)))
print('};\n#define SANDBOX_TRIGGER_COUNT %d\n' % len(triggers))

# emotes: TextEmotes enum and the lookup of the animation
source = open(root + '/Common/Constants/Emotes.cs', encoding='utf-8-sig').read()
numbers = dict((m.group(1), int(m.group(2))) for m in re.finditer(r'(EMOTE_[A-Z0-9_]+)\s*=\s*(\d+)', source))
lookup = re.findall(r'\{\s*TextEmotes\.(EMOTE_[A-Z0-9_]+),\s*(\d+)\s*\}', source)
print('static const SandboxEmote sandbox_emotes[] = {')
for name, animation in lookup:
    print('    {%d, %s},  /* %s */' % (numbers[name], animation, name))
print('};\n#define SANDBOX_EMOTE_COUNT %d\n' % len(lookup))
for name in ('EMOTE_SIT', 'EMOTE_STAND', 'EMOTE_SLEEP', 'EMOTE_KNEEL'):
    print('#define SANDBOX_%s %d' % (name, numbers[name]))
